import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SOURCE_ROOT = path.join(ROOT, 'public', 'images', 'generated');
const OUTPUT_FILE = path.join(ROOT, 'data', 'generatedSceneImages.ts');
const ALLOWED_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);

const normalizeTheme = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9çğıöşü_-]+/g, '')
    .trim();

const walkFiles = (dir) => {
  if (!fs.existsSync(dir)) return [];
  const items = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const item of items) {
    const nextPath = path.join(dir, item.name);
    if (item.isDirectory()) {
      files.push(...walkFiles(nextPath));
      continue;
    }
    files.push(nextPath);
  }
  return files;
};

const groupByTheme = (files) => {
  const grouped = {};
  for (const fullPath of files) {
    const ext = path.extname(fullPath).toLowerCase();
    if (!ALLOWED_EXT.has(ext)) continue;

    const relativeToSource = path.relative(SOURCE_ROOT, fullPath);
    const segments = relativeToSource.split(path.sep).filter(Boolean);
    if (segments.length < 2) continue;

    const theme = normalizeTheme(segments[0]);
    if (!theme) continue;

    const publicRelative = `/images/generated/${segments.join('/')}`;
    if (!grouped[theme]) grouped[theme] = [];
    if (!grouped[theme].includes(publicRelative)) grouped[theme].push(publicRelative);
  }

  return grouped;
};

const writeManifest = (grouped) => {
  const sortedThemes = Object.keys(grouped).sort((a, b) => a.localeCompare(b));
  const lines = [
    '// Auto-generated scene image pools.',
    '// Source: public/images/generated/<theme>/*',
    '// Generated by: scripts/build-generated-scene-images.mjs',
    "export const GENERATED_SCENE_IMAGE_POOLS: Record<string, string[]> = {",
  ];

  if (sortedThemes.length === 0) {
    lines.push('};');
  } else {
    for (const theme of sortedThemes) {
      lines.push(`  ${JSON.stringify(theme)}: [`);
      for (const file of grouped[theme]) {
        lines.push(`    ${JSON.stringify(file)},`);
      }
      lines.push('  ],');
    }
    lines.push('};');
  }

  fs.writeFileSync(OUTPUT_FILE, `${lines.join('\n')}\n`, 'utf8');
};

const files = walkFiles(SOURCE_ROOT);
const grouped = groupByTheme(files);
writeManifest(grouped);

const totalFiles = Object.values(grouped).reduce((acc, list) => acc + list.length, 0);
console.log(
  `[scene-manifest] themes=${Object.keys(grouped).length} files=${totalFiles} output=${path.relative(ROOT, OUTPUT_FILE)}`
);
